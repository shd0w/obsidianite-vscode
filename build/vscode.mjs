// 16 ANSI colors, shared by the VS Code terminal and the terminal ports.
export function ansi(flavor) {
  const p = flavor.colors;
  const light = flavor.type === "light";
  const bright = (hex) => mix(hex, light ? "#000000" : "#ffffff", light ? 0.12 : 0.18);
  return {
    black: light ? p.muted1 : p.layer1,
    red: p.garnet,
    green: p.peridot,
    yellow: p.citrine,
    blue: p.sapphire,
    magenta: p.amethyst,
    cyan: p.aquamarine,
    white: light ? p.layer2 : p.muted0,
    brightBlack: light ? p.veil1 : p.veil0,
    brightRed: bright(p.tourmaline),
    brightGreen: bright(p.peridot),
    brightYellow: bright(p.citrine),
    brightBlue: bright(p.sapphire),
    brightMagenta: bright(p.kunzite),
    brightCyan: bright(p.aquamarine),
    brightWhite: light ? p.veil0 : p.text,
  };
}

function terminalColors(flavor, prefix) {
  const out = {};
  for (const [k, v] of Object.entries(ansi(flavor))) {
    out[`${prefix}ansi${k[0].toUpperCase()}${k.slice(1)}`] = v;
  }
  return out;
}
